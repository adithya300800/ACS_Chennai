/**
 * Payslip Stage 1 — test fixtures.
 *
 * Shared by `payslip-sweep-safety.test.js` and (later rounds)
 * `payslip-publish-revoked-purge.test.js`. Keeps dummy employee ids,
 * dummy-payslip ULIDs, and the dummy PDF buffer in one place so a future
 * `payslipFactory({ overrides })` can compose a row without re-declaring
 * them.
 *
 * Privacy discipline (non-negotiable):
 *   * No real employee data. The employee ids below are
 *     `00000000-0000-0000-0000-{NNN...NNN}` so a typo can't accidentally
 *     resolve against a seeded real employee.
 *   * No salary figures anywhere. Not in the schema, not in the fixtures,
 *     not in any error message. The dummy PDF buffer below is a 1-byte
 *     `%PDF-` magic header — enough for the validator's shape check but
 *     no real salary content.
 *   * No source-text pin tests. Tests assert behavior, not exact line text.
 */

// Deterministic dummy employee UUIDs. The literal shape is the only
// identity — no row exists with this id in any test DB. The trailing
// digits are monotone so a future test can scan-skip through them
// (0001, 0002, 0003) without colliding with the real-shape uuids the
// fixtures might generate.
const DUMMY_EMPLOYEE_ID = '00000000-0000-0000-0000-000000000001';
const DUMMY_ADMIN_ID    = '00000000-0000-0000-0000-0000000000aa';

// Valid 26-char Crockford base32 ULIDs (the same regex the routes enforce).
// These are real Crockford ULIDs but with the timestamp stripped — they
// never resolve against the production ulid space because they were
// generated by hand, not by the canonical generator.
const DUMMY_PAYSLIP_ULID_1 = '01ARZ3NDEKTSV4RRFFQ69G5FAV';
const DUMMY_PAYSLIP_ULID_2 = '01BX5ZZKBKACTAV9WEVGEMMVRZ';

// Minimal valid PDF magic header — `%PDF-` followed by a version byte.
// The shape is enough for the magic-bytes validator (commit 3's
// verifyBlobMagicBytes) without carrying any salary content. The
// trailing `%%EOF` is the standard end-of-file marker; tests that
// exercise the upload route (commit 3+) need a parseable shape.
const dummyPdfBuffer = Buffer.from('%PDF-1.4\n%\xE2\xE3\xCF\xD3\n1 0 obj\n<<>>\nendobj\ntrailer\n<<>>\n%%EOF\n', 'binary');

/**
 * Build a single Payslip-shaped row for use in the protect-list tests.
 *
 * Default fields satisfy the schema's NOT-NULL columns (id, employeeId,
 * year, month, ulid, uploadIntentUlid, contentType, etag, sizeBytes,
 * blobPath, uploadedById, createdAt, updatedAt). Nullable fields
 * (publishedById, publishedAt, revokedById, revokedAt, revokedReason,
 * deletedAt) are intentionally null in the default — tests that need
 * a published / revoked / soft-deleted Payslip pass them via `overrides`.
 *
 * Why a factory instead of a static JSON:
 *   * The blob-path pattern (`payslips/{year}/{month}/{employeeId}/{ulid}.pdf`)
 *     is server-enforced (commit 3). Encoding it once prevents a future
 *     test from drifting to a wrong path and silently failing the
 *     protect-list match.
 *   * The dummy ULID defaults to DUMMY_PAYSLIP_ULID_1 so a protect-list
 *     test can seed an UploadIntent with the SAME ULID and prove the
 *     sweep's lookup-by-ulid includes it.
 *
 * @param {object} [overrides] - partial Payslip fields to override
 * @returns {object} a Payslip-shaped row (NOT a Prisma row — tests must
 *   not depend on Prisma decorators)
 */
function payslipFactory(overrides = {}) {
  const baseUlid = overrides.ulid || DUMMY_PAYSLIP_ULID_1;
  const baseEmployee = overrides.employeeId || DUMMY_EMPLOYEE_ID;
  const baseYear = overrides.year === undefined ? 2026 : overrides.year;
  const baseMonth = overrides.month === undefined ? 10 : overrides.month;
  const baseBlobPath = `payslips/${baseYear}/${String(baseMonth).padStart(2, '0')}/${baseEmployee}/${baseUlid}.pdf`;
  return {
    id: '00000000-0000-0000-0000-00000000aa01',
    employeeId: baseEmployee,
    year: baseYear,
    month: baseMonth,
    ulid: baseUlid,
    uploadIntentUlid: `int-${baseUlid}`,
    contentType: 'application/pdf',
    etag: 'etag-' + baseUlid,
    sizeBytes: BigInt(dummyPdfBuffer.length),
    blobPath: baseBlobPath,
    uploadedById: DUMMY_ADMIN_ID,
    publishedById: null,
    publishedAt: null,
    revokedById: null,
    revokedAt: null,
    revokedReason: null,
    deletedAt: null,
    createdAt: new Date('2026-10-02T00:00:00.000Z'),
    updatedAt: new Date('2026-10-02T00:00:00.000Z'),
    ...overrides,
  };
}

/**
 * Build a Prisma mock that serves `findMany` for the `payslip` delegate
 * only. Used by `payslip-sweep-safety.test.js` to seed protect-list data
 * without instantiating the real PrismaClient.
 *
 * Returns `{ payslip: { findMany: jest.fn() } }`. Tests set
 * `prisma.payslip.findMany.mockResolvedValue([...rows])` to control the
 * rows the sweep reads.
 *
 * Returns an object with the EXACT shape the sweep looks for: the
 * protect-list sources iterate `src.delegate.findMany(...)`, so any
 * delegate that lacks `findMany` makes the sweep hard-fail with the
 * "missing model" branch — which is the test contract (a real sweep
 * can never silently skip payslip rows).
 */
function buildPayslipPrisma(rows = []) {
  return {
    payslip: {
      findMany: jest.fn(async () => rows),
    },
  };
}

/**
 * Mock factory for the `verifyBlobMagicBytes` helper that ships in
 * commit 3. commit 2 tests that need to assert "blob was accepted as a
 * PDF" use this with `ok: true`; tests that need to assert "blob was
 * rejected" use `ok: false`. The three-state helper shape matches the
 * real helper's contract (`ok: true` / `ok: false` / `ok: null` for the
 * "could not HEAD the blob" 503 path).
 */
function mockVerifyBlobMagicBytes(threeState = 'ok') {
  const fn = jest.fn();
  if (threeState === 'ok') {
    fn.mockResolvedValue({ ok: true, contentType: 'application/pdf', sizeBytes: dummyPdfBuffer.length, etag: 'mock-etag' });
  } else if (threeState === 'not-pdf') {
    fn.mockResolvedValue({ ok: false, reason: 'NOT_PDF', observedMagic: 'image/jpeg' });
  } else if (threeState === 'head-failed') {
    fn.mockResolvedValue({ ok: null, reason: 'HEAD_FAILED' });
  } else {
    throw new Error(`mockVerifyBlobMagicBytes: unknown threeState ${threeState}`);
  }
  return fn;
}

module.exports = {
  DUMMY_EMPLOYEE_ID,
  DUMMY_ADMIN_ID,
  DUMMY_PAYSLIP_ULID_1,
  DUMMY_PAYSLIP_ULID_2,
  dummyPdfBuffer,
  payslipFactory,
  buildPayslipPrisma,
  mockVerifyBlobMagicBytes,
};